CREATE TABLE "warehouses" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(128) NOT NULL,
  "kind" warehouse_kind NOT NULL DEFAULT 'live',
  "created_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "zones" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "warehouse_id" bigint NOT NULL,
  "code" varchar(32) NOT NULL,
  "name" varchar(128) NOT NULL,
  "zone_type" zone_type NOT NULL,
  "tier_to_picking" access_tier,
  "tier_to_shipping" access_tier
);

CREATE TABLE "locations" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "warehouse_id" bigint NOT NULL,
  "zone_id" bigint NOT NULL,
  "zone_type" zone_type NOT NULL DEFAULT 'storage',
  "code" varchar(32) NOT NULL,
  "volume_capacity_dm3" numeric(12,3) NOT NULL,
  "max_weight_kg" numeric(12,3) NOT NULL,
  "max_length_mm" integer NOT NULL,
  "max_width_mm" integer NOT NULL,
  "max_height_mm" integer NOT NULL,
  "distance_to_receiving_m" numeric(10,2) NOT NULL,
  "distance_to_picking_m" numeric(10,2) NOT NULL,
  "distance_to_shipping_m" numeric(10,2) NOT NULL,
  "is_active" boolean NOT NULL DEFAULT true,
  "occupied_volume_dm3" numeric(12,3) NOT NULL DEFAULT 0,
  "occupied_weight_kg" numeric(12,3) NOT NULL DEFAULT 0,
  "version" bigint NOT NULL DEFAULT 0
);

CREATE TABLE "compat_groups" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
